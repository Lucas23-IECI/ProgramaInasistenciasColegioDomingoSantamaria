CREATE TABLE IF NOT EXISTS politicas_retencion (
  categoria VARCHAR(40) PRIMARY KEY
    CHECK (categoria IN ('RUT_TELEFONOS', 'AUDITORIA', 'DOCUMENTOS', 'VISITAS_RETIROS')),
  dias_retencion INT CHECK (dias_retencion IS NULL OR dias_retencion BETWEEN 30 AND 3650),
  modo VARCHAR(30) NOT NULL DEFAULT 'SOLO_PREVISUALIZAR'
    CHECK (modo IN ('SOLO_PREVISUALIZAR', 'APROBADA_SIN_EJECUTAR')),
  fundamento VARCHAR(1000),
  actualizado_por INT REFERENCES usuarios(id) ON DELETE SET NULL,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

